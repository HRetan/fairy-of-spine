/** 알림 한 건. 가끔 아스키 아트가 딸려 온다. */
export function reminderMessage(): FairyMessage {
  const text = pick(REMINDERS);
  return Math.random() < ART_CHANCE ? { text, art: pick(ARTS) } : { text };
}

export function greetingMessage(): string {
  return pick(GREETINGS);
}

export function praiseMessage(): string {
  return pick(PRAISES);
}

/** 앞뒤 빈 줄만 걷어낸다. 각 줄의 들여쓰기는 그대로 둬야 그림이 유지된다. */
function block(art: string): string {
  return art.replace(/^\n/, "").replace(/\n\s*$/, "");
}

function pick<T>(items: readonly T[]): T {
  // 목록이 비어 있을 일은 없지만 타입상 undefined 가능성을 없앤다.
  return items[Math.floor(Math.random() * items.length)] ?? items[0]!;
}
